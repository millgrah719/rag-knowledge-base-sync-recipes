import assert from 'node:assert/strict';
import fs from 'node:fs';
const wf=JSON.parse(fs.readFileSync(new URL('../n8n/rag-dataset-qa.json',import.meta.url),'utf8'));
const node=name=>wf.nodes.find(n=>n.name===name);
const execute=(name,input,refs={})=>new Function('$input','$',node(name).parameters.jsCode)({first:()=>({json:input})},name=>({first:()=>({json:refs[name]})}));
const run={id:'fixture-run',status:'SUCCEEDED',defaultKeyValueStoreId:'fixture-store',defaultDatasetId:'fixture-dataset'};
assert.equal(wf.active,false);
assert.equal(execute('Choose input',{})[0].json.inputMode,'demo');
assert.equal(execute('Require successful run',{data:run})[0].json.id,run.id);
for(const status of ['RUNNING','FAILED','ABORTED','TIMED-OUT']) assert.throws(()=>execute('Require successful run',{data:{...run,status}}));
assert.throws(()=>execute('Require successful run',{data:{status:'SUCCEEDED'}}));
for(const status of ['BILLING_UNKNOWN','BUDGET_LIMIT','FAILED']) assert.throws(()=>execute('Require complete report',{status},{'Require successful run':run}));
const complete=execute('Require complete report',{status:'COMPLETE',baselineEligible:true},{'Require successful run':run})[0].json;
const refs={'Require complete report':complete,'Read QA':{duplicateRows:1}};
const result=execute('Review result',{body:[{operation:'UPSERT',chunkId:'a'},{operation:'DELETE',chunkId:'b'}]},refs)[0].json;
assert.equal(result.upserts.length,1);
assert.equal(result.deleteSuggestions.length,1);
assert.equal(result.baselineEligible,true);
assert.equal(execute('Review result',{body:[]},refs)[0].json.upserts.length,0);
assert.throws(()=>execute('Review result',{body:{}},refs));
assert.equal(wf.nodes.filter(n=>n.type==='n8n-nodes-base.httpRequest').length,4);
assert(!wf.nodes.some(n=>n.credentials));
assert(!JSON.stringify(wf).includes('apify_api_'));
assert.match(node('Start Apify report').parameters.url,/maxTotalChargeUsd=0\.75/);
assert.equal(node('Start Apify report').retryOnFail,undefined);
console.log('PASS: workflow structure, demo defaults, run and report gates, empty and invalid results, operation separation, credential-free export, capped run and no automatic POST retry. Code-node fixture tests only; not a complete n8n runtime test.');
